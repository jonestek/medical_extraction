# retrieve the API key from Colab Secrets and initialize the client
try:
    api_key = userdata.get('OpenAI')
    client = OpenAI(api_key=api_key)
    print("API Key retrieved and OpenAI client initialized successfully.")
except userdata.SecretNotFoundError:
    print("Error: The secret 'OpenAI' was not found in your Colab secrets.")

# load csv file
df = pd.read_csv("/content/medical_transcription_dataset.csv")

# define the structured schema using Pydantic-style JSON schema
medical_data_schema = {
    "name": "extract_medical_data",
    "strict": True,
    "schema": {
        "type": "object",
        "properties": {
            "Age": {
                "type": "string",
                "description": "Age of the patient or 'Unknown'"
            },
            "Recommended Treatment/Procedure": {
                "type": "string",
                "description": "Recommended treatment or procedure for the patient or 'Unknown'"
            }
        },
        "required": ["Age", "Recommended Treatment/Procedure"],
        "additionalProperties": False
    }
}

def extract_info_with_openai(transcription):
    """Extracts age and recommended treatment from a transcription using OpenAI Structured Outputs."""
    # Defensive check for empty or missing transcriptions
    if pd.isna(transcription) or not str(transcription).strip():
        return {"Age": "Unknown", "Recommended Treatment/Procedure": "Unknown"}

    messages = [
        {
            "role": "system",
            "content": (
                "You are an automated medical data extraction system. Your sole task is to extract "
                "the patient's age and recommended treatment/procedure from the provided text into the required JSON schema. "
                "Do not include any conversational filler. If the text does not contain medical information, "
                "or if specific data points are missing, strictly set those fields to 'Unknown'."
            )
        },
        {
            "role": "user",
            "content": f"Transcription to extract data from: {transcription}"
        }
    ]

    try:
        # Note: If not using a Pydantic class 'MedicalData', you can pass the schema dictionary as:
        # response_format={"type": "json_schema", "json_schema": medical_data_schema}
        response = client.beta.chat.completions.parse(
            model="gpt-4o-mini",
            messages=messages,
            temperature=0,
            response_format={"type": "json_schema", "json_schema": medical_data_schema}
        )

        parsed_output_str = response.choices[0].message.content
        if parsed_output_str:
            parsed_output = json.loads(parsed_output_str)
            return {
                "Age": parsed_output.get("Age", "Unknown"),
                "Recommended Treatment/Procedure": parsed_output.get("Recommended Treatment/Procedure", "Unknown")
            }

    except Exception as e:
        print(f"OpenAI API Request Error: {e}")

    return {"Age": "Unknown", "Recommended Treatment/Procedure": "Unknown"}


# process data cleanly using Pandas .apply() instead of old iterrows loop
print("Processing transcriptions... (This might take a moment depending on dataset size)")

# extract age and treatment into a series of dictionaries
extracted_series = df['transcription'].apply(extract_info_with_openai)

# build new structured dataFrame
df_structured = pd.DataFrame(list(extracted_series))

# seamlessly map over and append structural variables
df_structured["Medical Specialty"] = df["medical_specialty"]

# display the final processed structured output
print("\nProcessing complete! Final Output Preview:")
print(df_structured.head())

